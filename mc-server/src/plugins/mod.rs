//! 이 서버만의 기능 (바닐라에 없는 것). 기능 하나 = 폴더 하나.
//!
//! 폴더 안은 대체로 이렇게 나눕니다.
//! - `mod.rs`  규칙·상태·저장 (패킷을 모름 — 단위 테스트하기 쉬움)
//! - `gui.rs` / `session.rs`  플레이어 접속(`Session`)에 붙는 부분: 명령어, 창, 클릭
//! - 그 밖에 그림·모델 같은 내용물
//!
//! | 폴더 | 하는 일 |
//! |---|---|
//! | [`chat`]     | 채팅 채널: 전체·채널·주변·거래·길드·관리자, `/채널`, 앞 기호 |
//! | [`contents`] | ItemsAdder 호환 콘텐츠: 설정·그림 → 아이템·블록·이모지·리소스 팩, `/ia` 목록 |
//! | [`lottery`]  | 채널별 주간 복권: 번호 고르기 창, 일련번호 복권, 추첨·당첨금 |
//! | [`equip`]    | 장비: 세트·+30 강화·악세 잠재능력·주문서·광물 6종·대장간·보스 |
//! | [`guild`]    | 길드: 정보·창고(페이지·기록)·땅(보호)·청크 지도·작물 촉진제·업그레이드·신호기·2배 이벤트·역할 권한 |
//! | [`hotreload`] | 핫 리로드: contents/·장비 그림이 바뀌면 팩을 새로 만들어 다시 보냄 |
//! | [`hud`]      | 화면 HUD: 왼쪽 위 재화, 오른쪽 위 퀘스트, 오른쪽 아래 스탯, 핫바 위 체력·마나바 (폰트 + 셰이더) |
//! | [`menu`]     | 퀵메뉴 (Shift+F): 광장·마을·야생·던전·레이드 이동, 워프, 내 정보·생활/모험가 스탯, 길라잡이, 후원, 링크, 설정, 쓰레기통 |
//! | [`npc`]      | Citizens 비슷한 NPC: `/npc`, 스킨, 말·명령·동작 |
//! | [`quest`]    | 퀘스트: 일반·주간·길드 주간, `/퀘스트` 창, HUD 오른쪽 위 |
//! | [`rank`]     | 후원 등급 Budget·VIP·MVP: /ec /제작대 /셋홈 /홈, 마을 플라이·더블점프, 인벤세이브, 잠수·경험치 배율, 자동심기, 갑옷 숨기기 |
//! | [`rpg`]      | RPG 스탯 계산 (레벨·공격력·방어력·전투력) |
//! | [`rules`]    | 서버 규칙: 금지 아이템 (제작·드랍 막기) |
//! | [`store`]    | 여러 인스턴스가 함께 쓰는 JSON 파일 (잠금 + 바뀌면 다시 읽기) |
//! | [`webadmin`] | 웹 관리 화면: 길드 레벨별 효과·강화·작물 단계·창고 막기, 퀘스트 편집 |

